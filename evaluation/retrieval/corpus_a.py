"""Hand-written evaluation clusters (part A). Each cluster is a small world with records, relations
and queries. Records: R(key, text, **flags). Flags: agent=True (recorded by an agent, unconfirmed:
outside the user projection), forget/retract=True (lifecycle already applied), date="YYYY-MM-DD"
(authored/captured time). Queries: Q(id, text, gold, cat, ...)."""


def R(key, text, **flags):
    return {"key": key, "text": text, **flags}


def Q(qid, text, gold, cat, **kw):
    return {"id": qid, "text": text, "gold": gold, "cat": cat, **kw}


# Expected intent/depth labels use the planner vocabulary; they are annotations written before
# running the planner, derived from the query's wording, not from planner output.
